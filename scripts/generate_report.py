def main():
    if not SCORES_FILE.exists() or not TIMESTAMPS_FILE.exists():
        print("[ERROR] Missing input files. Run compare_phonemes.py and align_phonemes_dtw.py first.")
        return

    with open(SCORES_FILE, "r") as f:
        raw_data = json.load(f)
        # Create a lookup map: "filepath" -> score
        # We assume file paths in JSON match the ones generated by slice_phonemes
        # We need to normalize paths to avoid slash issues
        score_map = {}
        for item in raw_data["per_slice"]:
            # extract "0003_hello_OW1" from path
            fname = Path(item["file"]).name
            score_map[fname] = item["similarity"]

    with open(TIMESTAMPS_FILE, "r") as f:
        # This contains the word/phoneme structure ordered by time
        alignment_data = json.load(f)

    final_report = {
        "overall_score": 0,
        "details": []
    }

    total_score = 0
    count = 0

    # Group by word
    current_word_idx = -1
    current_word_obj = None

    for entry in alignment_data:
        w_idx = entry["word_index"]
        word_text = entry["word"]
        ph = entry["phoneme"]
        
        # New word group?
        if w_idx != current_word_idx:
            if current_word_obj:
                # Calculate word average before pushing
                w_scores = [p["score"] for p in current_word_obj["phonemes"]]
                current_word_obj["word_score"] = int(np.mean(w_scores)) if w_scores else 0
                grade, color = get_grade(current_word_obj["word_score"])
                current_word_obj["grade"] = grade
                current_word_obj["color"] = color
                final_report["details"].append(current_word_obj)

            current_word_idx = w_idx
            current_word_obj = {
                "word": word_text,
                "word_score": 0,
                "phonemes": []
            }

        # Construct filename key to look up score
        # slice_phonemes.py naming: f"{i:04d}_{safe_word}_{p['phoneme']}.wav"
        # We need to reconstruct the index 'i' relative to the full list?
        # Actually, let's just match loosely or assume 'alignment_data' order matches 'score_map'?
        # Better: slice_phonemes used a global counter. We need to match that.
        # FIX: The score_map keys look like "0000_hello_HH.wav". 
        # We can just match by "word" and "phoneme" if unique, or we need to track index.
        # Let's rely on the fact that slice_phonemes iterates exactly like alignment_data.
        
        # We need the global index `count` to match filenames like 0000_...
        safe_word = "".join(c for c in word_text if c.isalnum() or c in ("_","-")).lower()
        fname = f"{count:04d}_{safe_word}_{ph}.wav"
        
        raw_sim = score_map.get(fname, 0.0) # Default to 0 if missing
        
        # Normalize
        final_score = normalize_score(raw_sim, ph)
        grade, color = get_grade(final_score)

        current_word_obj["phonemes"].append({
            "phoneme": ph,
            "raw_similarity": raw_sim,
            "score": final_score,
            "grade": grade,
            "color": color,
            "start": entry["start"],
            "end": entry["end"]
        })
        
        total_score += final_score
        count += 1

    # Push last word
    if current_word_obj:
        w_scores = [p["score"] for p in current_word_obj["phonemes"]]
        current_word_obj["word_score"] = int(np.mean(w_scores)) if w_scores else 0
        grade, color = get_grade(current_word_obj["word_score"])
        current_word_obj["grade"] = grade
        current_word_obj["color"] = color
        final_report["details"].append(current_word_obj)

    # Final Average
    final_report["overall_score"] = int(total_score / count) if count > 0 else 0
    
    # Save
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        json.dump(final_report, f, indent=2)

    print(f"\n[SUCCESS] Generated Assessment Report: {OUT_FILE}")
    print(f"Overall Score: {final_report['overall_score']}/100")

if __name__ == "__main__":
    main()