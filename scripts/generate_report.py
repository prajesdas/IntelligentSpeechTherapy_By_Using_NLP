# scripts/generate_report.py
import json
import numpy as np
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCORES_FILE = ROOT / "metadata" / "phoneme_similarity_scores.json"
TIMESTAMPS_FILE = ROOT / "metadata" / "phoneme_timestamps.json"
OUT_FILE = ROOT / "metadata" / "assessment_report.json"

# --- CONFIGURATION ---
# Short consonants are naturally harder to capture, so we grade them on a curve.
SHORT_SOUNDS = ["P", "B", "T", "D", "K", "G", "F", "V", "TH", "DH", "S", "Z", "SH", "ZH", "CH", "JH"]

def get_grade(score):
    """Converts a normalized score (0-100) into a grade."""
    if score >= 70: return "Good", "green"
    if score >= 40: return "Average", "yellow"
    return "Needs Improvement", "red"

def normalize_score(raw_sim, phoneme):
    """
    Calibrated Teacher Logic for Non-Native Speakers.
    """
    # 1. Clamp negative to 0
    score = max(0.0, raw_sim)
    
    # 2. Stronger Boost for Consonants
    # "Strict Math" sees 0.40 as bad. "Human Teacher" sees 0.40 as Good for 'K' or 'T'.
    if phoneme in SHORT_SOUNDS:
        # Formula: y = x^0.5 (Square Root Curve) - Very forgiving for low numbers
        # 0.10 -> 0.31
        # 0.25 -> 0.50
        # 0.40 -> 0.63 (Green)
        score = np.power(score, 0.5)
    else:
        # Vowels: Linear scaling but boosted 
        # 0.60 -> 0.76
        # 0.70 -> 0.85
        score = (score * 0.8) + 0.2 if score > 0.1 else score

    # 3. Scale to 0-100
    final_score = int(score * 100)
    
    # Cap at 100
    return min(100, final_score)

